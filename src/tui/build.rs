use std::collections::BTreeMap;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const DEFAULT_LAYOUT: &str = "classic";

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut",
    "pub", "ref", "return", "self", "Self", "static", "struct", "super", "trait", "true", "type",
    "unsafe", "use", "where", "while",
];

fn main() {
    let manifest_dir =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR is set"));
    let layouts_dir = manifest_dir.join("src").join("layouts");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", layouts_dir.display());

    let entries = discover_layouts(&layouts_dir);
    assert!(
        !entries.is_empty(),
        "no TUI layouts found in {}",
        layouts_dir.display()
    );

    let mut ordered: Vec<(String, PathBuf)> = entries.into_iter().collect();
    ordered.sort_by(|(a, _), (b, _)| {
        let a_default = a == DEFAULT_LAYOUT;
        let b_default = b == DEFAULT_LAYOUT;
        b_default.cmp(&a_default).then_with(|| a.cmp(b))
    });

    let mut code = String::from("// Generated by src/tui/build.rs — do not edit by hand.\n\n");
    for (id, path) in &ordered {
        let normalized = path
            .to_str()
            .expect("layout path must be valid UTF-8")
            .replace('\\', "/");
        code.push_str(&format!("#[path = \"{normalized}\"]\nmod {id};\n"));
    }

    code.push_str("\n/// Every compiled-in layout plugin, default (`classic`) first.\npub static LAYOUTS: &[&dyn TuiLayout] = &[\n");
    for (id, _) in &ordered {
        code.push_str(&format!("    &{id}::LAYOUT,\n"));
    }
    code.push_str("];\n\n/// Layout identifiers in the same order as [`LAYOUTS`], for Settings choices.\npub const LAYOUT_IDS: &[&str] = &[\n");
    for (id, _) in &ordered {
        code.push_str(&format!("    \"{id}\",\n"));
    }
    code.push_str("];\n");

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR is set"));
    fs::write(out_dir.join("layouts_registry.rs"), code)
        .expect("failed to write generated layouts_registry.rs");
}

fn discover_layouts(layouts_dir: &Path) -> BTreeMap<String, PathBuf> {
    let mut found: BTreeMap<String, PathBuf> = BTreeMap::new();
    let read_dir = fs::read_dir(layouts_dir)
        .unwrap_or_else(|err| panic!("failed to read {}: {err}", layouts_dir.display()));

    for entry in read_dir {
        let entry = entry.expect("failed to read directory entry in src/layouts");
        let path = entry.path();
        let file_type = entry
            .file_type()
            .expect("failed to inspect file type in src/layouts");

        if file_type.is_dir() {
            println!("cargo:rerun-if-changed={}", path.display());
            let mod_rs = path.join("mod.rs");
            if !mod_rs.is_file() {
                // Ignore empty directories left behind by branch switches.
                continue;
            }
            println!("cargo:rerun-if-changed={}", mod_rs.display());
            let id = path
                .file_name()
                .and_then(|n| n.to_str())
                .expect("layout directory name must be valid UTF-8");
            validate_layout_id(id, &path);
            if let Some(prev) = found.insert(id.to_string(), mod_rs) {
                panic!(
                    "duplicate TUI layout id `{id}`: both {} and {} exist",
                    prev.display(),
                    path.display()
                );
            }
        } else if file_type.is_file() && path.extension().and_then(|e| e.to_str()) == Some("rs") {
            let stem = path
                .file_stem()
                .and_then(|n| n.to_str())
                .expect("layout file stem must be valid UTF-8");
            if stem == "mod" {
                println!("cargo:rerun-if-changed={}", path.display());
                continue;
            }
            println!("cargo:rerun-if-changed={}", path.display());
            validate_layout_id(stem, &path);
            if let Some(prev) = found.insert(stem.to_string(), path.clone()) {
                panic!(
                    "duplicate TUI layout id `{stem}`: both {} and {} exist",
                    prev.display(),
                    path.display()
                );
            }
        }
    }

    found
}

fn validate_layout_id(id: &str, path: &Path) {
    let mut chars = id.chars();
    let valid_ident = chars.next().is_some_and(|c| c.is_ascii_lowercase())
        && chars.all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    assert!(
        valid_ident && !RUST_KEYWORDS.contains(&id),
        "invalid TUI layout identifier `{id}` at {} (expected lowercase `[a-z][a-z0-9_]*`, non-keyword)",
        path.display()
    );
}
